"""Static research figures (PNG), an interactive Plotly comparison (HTML) and tables for the report."""
from __future__ import annotations

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import plotly.express as px
import seaborn as sns

from src.common import get_logger, resolve
from src.model_evaluation.evaluate import save_evaluation_plots
from src.schema import SURVEY_DIMENSIONS, SURVEY_ITEMS

log = get_logger(__name__)


def make_figures(clean, ev, full, rs, survey, results, scores, y_te, cfg) -> None:
    fig_dir = resolve(cfg, "figures")
    sns.set_theme(style="whitegrid")
    hour = pd.to_datetime(clean["timestamp"]).dt.hour

    fig, ax = plt.subplots(1, 3, figsize=(16, 4.2))
    clean.groupby(hour)["is_fraud"].mean().mul(100).plot.bar(ax=ax[0], color="#c1121f")
    ax[0].set(title="Fraud rate by hour of day", xlabel="hour", ylabel="% fraudulent")
    sns.kdeplot(data=clean.assign(cls=clean.is_fraud.map({0: "legit", 1: "fraud"})), x="amount", hue="cls",
                log_scale=True, common_norm=False, ax=ax[1])
    ax[1].set(title="Amount distribution (log scale)")
    clean.groupby("merchant_category")["is_fraud"].mean().mul(100).sort_values().plot.barh(ax=ax[2], color="#2a6f97")
    ax[2].set(title="Fraud rate by merchant category", xlabel="% fraudulent")
    fig.tight_layout(); fig.savefig(fig_dir / "transaction_overview.png", dpi=130); plt.close(fig)

    fig, ax = plt.subplots(1, 2, figsize=(12, 4))
    daily = ev.assign(day=pd.to_datetime(ev.timestamp).dt.normalize()).groupby(["day", "is_attack"]).size().unstack(fill_value=0)
    daily.rename(columns={0: "benign", 1: "attack"}).plot(ax=ax[0]); ax[0].set(title="Security events per day")
    ev[ev.is_attack == 1].groupby("event_type").size().sort_values().plot.barh(ax=ax[1], color="#7b2cbf")
    ax[1].set(title="Attack events by type")
    fig.tight_layout(); fig.savefig(fig_dir / "security_overview.png", dpi=130); plt.close(fig)

    fig, ax = plt.subplots(1, 3, figsize=(16, 4.2))
    sns.histplot(rs["trust_score"], bins=25, kde=True, ax=ax[0], color="#2a9d8f"); ax[0].set(title="Consumer Trust Score distribution")
    rs[SURVEY_DIMENSIONS].mean().sort_values().plot.barh(ax=ax[1], color="#e9c46a"); ax[1].set(title="Mean score per dimension (0-100)")
    corr = full[[*SURVEY_ITEMS, "trust_score", "uses_mfa", "experienced_fraud", "digital_literacy"]].corr(method="spearman")
    sns.heatmap(corr, cmap="vlag", center=0, ax=ax[2], cbar_kws={"shrink": .7}); ax[2].set(title="Spearman correlations")
    fig.tight_layout(); fig.savefig(fig_dir / "consumer_trust_overview.png", dpi=130); plt.close(fig)

    fig, ax = plt.subplots(figsize=(8, 4))
    sns.boxplot(data=full, x="age_band", y="trust_score", order=["18-24", "25-34", "35-44", "45-54", "55+"], ax=ax, color="#8ecae6")
    ax.set(title="Trust score by age band")
    fig.tight_layout(); fig.savefig(fig_dir / "trust_by_age.png", dpi=130); plt.close(fig)

    save_evaluation_plots(y_te, scores, results, fig_dir)

    df = pd.DataFrame(results).T.reset_index(names="model")[["model", "precision", "recall", "f1", "roc_auc", "pr_auc"]]
    long = df.melt("model", var_name="metric", value_name="value")
    px.bar(long, x="model", y="value", color="metric", barmode="group",
           title="Test-set model comparison (interactive)").write_html(fig_dir / "model_comparison.html")


def write_tables(table, risk, trust, corr, ols_df, rel, checks, external) -> None:
    from src.common import ROOT
    out = ROOT / "report" / "tables"
    out.mkdir(parents=True, exist_ok=True)
    table.round(4).to_csv(out / "model_comparison.csv")
    risk.to_csv(out / "risk_tiers.csv", index=False)
    corr.to_csv(out / "trust_driver_correlations.csv", index=False)
    ols_df.round(4).to_csv(out / "trust_ols.csv")
    pd.DataFrame(checks).to_csv(out / "data_validation.csv", index=False)
    pd.Series(rel, name="cronbach_alpha").round(3).to_csv(out / "reliability.csv")
    if external:
        pd.DataFrame(external).T.round(4).to_csv(out / "external_benchmark_creditcard.csv")
    md = ["# Auto-generated results (do not edit - regenerated by `make pipeline`)", "",
          "## Model comparison (held-out chronological test set)", "", table.round(4).to_markdown(), "",
          "## Risk tiers (champion model)", "", risk.round(4).to_markdown(index=False), "",
          "## Consumer trust", "",
          f"- Respondents: {trust['n_respondents']}",
          f"- Mean Consumer Trust Score: {trust['mean_trust_score']:.1f}/100",
          f"- Platform Security Index: {trust['platform_security_index']:.1f}/100",
          f"- Consumer Trust Index: {trust['consumer_trust_index']:.1f}/100",
          f"- Cronbach's alpha (all items): {rel['overall']:.3f}", "",
          "### Driver correlations (Spearman)", "", corr.round(4).to_markdown(index=False), ""]
    (out / "results_summary.md").write_text("\n".join(md), encoding="utf-8")
