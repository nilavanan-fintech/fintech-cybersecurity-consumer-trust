"""Review 3 - ML implementation, fraud/anomaly detection, trust scoring, experiments, Grafana development.
Numbers come from models/model_metadata/last_run_summary.json (real pipeline output); the deck refuses to build without it."""
from theme import ROOT, Deck, load_summary

FIG = ROOT / "report" / "figures"


def build():
    s = load_summary()
    R, tr = s["models"]["results"], s["models"]["train"]
    d = Deck(3, "Machine Learning, Anomaly Detection, Trust Scoring and Dashboards")
    d.bullets("Progress since Review 2", [
        "Supervised models implemented: Logistic Regression, Random Forest, XGBoost with randomised hyper-parameter search",
        "Unsupervised detectors implemented: Isolation Forest, Local Outlier Factor",
        "Risk tiers, consumer trust scoring and statistics helpers implemented",
        "Prometheus exporter, PostgreSQL persistence and 7 provisioned Grafana dashboards developed",
        "Preliminary experiments run; results are first-run numbers on synthetic data, not final"])
    d.table("Machine learning implementation", ["Model", "Role", "Imbalance handling", "Tuned parameters"], [
        ["Logistic Regression", "Interpretable baseline", "class_weight=balanced", "C"],
        ["Random Forest", "Non-linear bagging", "balanced_subsample", "max_depth, min_samples_leaf, max_features"],
        ["XGBoost", "Boosted trees", "scale_pos_weight", "depth, learning rate, subsample, colsample, min_child_weight"],
        ["Isolation Forest / LOF", "Label-free detectors", "contamination parameter", "none (fit without labels)"]],
        widths=[2.7, 2.7, 2.6, 4.1], note="Protocol: randomised search (average precision) on train; F1-optimal threshold on validation; test used once.")
    d.flow("Fraud and anomaly detection flow", ["Cleaned transactions", "Features (40)", "Train/validation/test (chronological)", "Supervised models",
                                                 "Unsupervised detectors", "Metrics + risk tiers", "Security events -> Isolation Forest", "Prometheus + PostgreSQL"], cols=4)
    names = list(R)
    d.bar_chart("Preliminary experiment: PR-AUC and ROC-AUC (test set)", names,
                {"PR-AUC": [R[n]["pr_auc"] for n in names], "ROC-AUC": [R[n]["roc_auc"] for n in names]},
                f"Real first-run output (run {s['run_id']}). Tuning budget n_iter is small; test set has {R[names[0]]['tp'] + R[names[0]]['fn']} fraud cases, so estimates are noisy.")
    d.table("Preliminary experiment: threshold metrics", ["Model", "Precision", "Recall", "F1", "FPR"],
            [[n, f"{R[n]['precision']:.3f}", f"{R[n]['recall']:.3f}", f"{R[n]['f1']:.3f}", f"{R[n]['false_positive_rate']:.4f}"] for n in names],
            widths=[3.5, 2.1, 2.1, 2.1, 2.3], note="Synthetic data: use these to validate the pipeline, not to claim real-world performance.")
    t = s["trust"]
    d.table("Consumer trust scoring (synthetic survey)", ["Quantity", "Value"], [
        ["Respondents", t["n_respondents"]], ["Mean Consumer Trust Score (0-100)", f"{t['mean_trust_score']:.1f}"],
        ["Platform Security Index (0-100)", f"{t['platform_security_index']:.1f}"], ["Consumer Trust Index (0-100)", f"{t['consumer_trust_index']:.1f}"],
        ["Cronbach alpha (all items)", f"{t['cronbach_alpha']['overall']:.3f}"], ["Min k-anonymity group", t["k_anonymity_min_group"]]],
        widths=[6.5, 5.6], note="Survey data is synthetic placeholder data; the index is a proposed composite pending sensitivity analysis and real responses.")
    p = FIG / "roc_pr_curves.png"
    d.image("Experimental work: ROC and precision-recall curves", p, "Generated by src/model_evaluation/evaluate.py from the held-out test partition.")
    d.table("Grafana dashboard development", ["Dashboard", "Data sources", "Status"], [
        ["Research Overview", "Prometheus, Loki", "Provisioned"], ["Transaction & Fraud Analytics", "Prometheus, PostgreSQL", "Provisioned"],
        ["Cybersecurity Threat Monitoring", "Prometheus, PostgreSQL, Loki", "Provisioned"], ["Consumer Trust Indicators", "Prometheus, PostgreSQL", "Provisioned"],
        ["ML Model Performance", "Prometheus, PostgreSQL", "Provisioned"], ["Data Pipeline Monitoring", "Prometheus, PostgreSQL, Loki", "Provisioned"],
        ["Docker Infrastructure Health", "Prometheus (cAdvisor)", "Provisioned"]], widths=[4.6, 4.6, 2.9],
        note="Panels query metrics computed by the pipeline and a held-out replay through the trained model; no hardcoded values.")
    for f, cap in (("review/assets/grafana_overview.png", "Grafana: Research Overview"), ("review/assets/grafana_pipeline.png", "Grafana: Pipeline Monitoring")):
        if (ROOT / f).exists():
            d.image(cap, ROOT / f, "Screenshot captured from the running stack.")
    d.bullets("Issues, risks and next steps", [
        "Increase tuning budget and repeat on several seeds for stable estimates",
        "Run the optional public credit-card benchmark",
        "Replace synthetic survey with real, ethics-approved responses",
        "Finish sensitivity analysis of the trust index; write results chapters (Review 4)"])
    d.save("review_3.pptx")


if __name__ == "__main__":
    build()
